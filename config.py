"""
Файл конфигурации отслеживания билетов на поезда БелЖД (pass.rw.by).
Параметры и секреты подтягиваются из файла окружения .env и/или routes.json.
"""

import json
import os
from pathlib import Path
from dotenv import load_dotenv

# Базовая директория проекта
BASE_DIR = Path(__file__).resolve().parent

# Загружаем переменные окружения из .env (если файл существует)
env_path = BASE_DIR / ".env"
if env_path.exists():
    load_dotenv(dotenv_path=env_path)
else:
    load_dotenv()


# ==============================================================================
# 1. НАСТРОЙКИ TELEGRAM (Считываются из .env)
# ==============================================================================
BOT_TOKEN = os.getenv("TELEGRAM_BOT_TOKEN") or os.getenv("BOT_TOKEN", "")
CHAT_ID = os.getenv("TELEGRAM_CHAT_ID") or os.getenv("CHAT_ID", "")


# ==============================================================================
# 2. ПАРАМЕТРЫ РАБОТЫ СКРИПТА (Считываются из .env с значениями по умолчанию)
# ==============================================================================
# Интервал между проверками в секундах
CHECK_INTERVAL = int(os.getenv("CHECK_INTERVAL", "15"))

# Фоновый режим (True — окно браузера скрыто, False — показывать окно)
HEADLESS = os.getenv("HEADLESS", "True").strip().lower() in ("true", "1", "yes")

# Прикреплять скриншоты страниц расписания к сообщению в Telegram (True / False)
SEND_SCREENSHOT = os.getenv("SEND_SCREENSHOT", "True").strip().lower() in ("true", "1", "yes")

# Звуковой сигнал на компьютере при появлении билета (True / False)
SOUND_ALERT = os.getenv("SOUND_ALERT", "True").strip().lower() in ("true", "1", "yes")


# ==============================================================================
# 3. МАРШРУТЫ И ДАТЫ ДЛЯ ОТСЛЕЖИВАНИЯ
# ==============================================================================
# Маршруты можно задавать:
# 1) В отдельном файле routes.json (рекомендуется, файл не попадает в git)
# 2) Либо в списке DEFAULT_ROUTES ниже

# ------------------------------------------------------------------------------
# ℹ️ СПРАВОЧНИК ПО ПАРАМЕТРАМ:
# ------------------------------------------------------------------------------
# • "from" / "to":
#     Станции отправления и прибытия точно как на pass.rw.by
#     Примеры: "Минск-Пассажирский", "Пинск", "Брест-Центральный", "Гродно", "Гомель"
#
# • "date":
#     Дата поездки в формате "ГГГГ-ММ-ДД" (например: "2026-10-23")
#
# • "train" (Фильтр по номеру поезда):
#     ""       -> Любой подходящий поезд на эту дату (рекомендуется)
#     "657Б"   -> Межрегиональный эконом (обычный ночной/дневной со спальными вагонами)
#     "727Б"   -> Межрегиональный бизнес (скоростной Stadler / дизель-поезд)
#     "028Б"   -> Международный поезд (например в Москву/СПб)
#
# • "car_types" (Фильтр по типам вагонов / мест):
#     []                     -> Любые свободные места (рекомендуется)
#     ["Плацкарт"]           -> Только плацкартные вагоны
#     ["Купе"]               -> Только купейные вагоны
#     ["Плацкарт", "Купе"]   -> И плацкарт, и купе
#     ["Сидячий"]            -> Сидячие места (актуально для Штадлеров и бизнес-класса)
#     ["СВ"]                 -> СВ / Люкс (двухместные купе)
#     ["Общий"]              -> Общие вагоны
# ------------------------------------------------------------------------------

DEFAULT_ROUTES = [
    {
        "name": "ТУДА (Минск ➔ Брест)",
        "from": "Минск-Пассажирский",
        "to": "Брест-Центральный",
        "date": "2026-12-30",
        "train": "",
        "car_types": []
    },
    {
        "name": "ОБРАТНО (Брест ➔ Минск)",
        "from": "Брест-Центральный",
        "to": "Минск-Пассажирский",
        "date": "2027-01-03",
        "train": "727Б, 657Б",
        "car_types": ["Плацкарт", "Купе"]
    }
]


def load_routes() -> list:
    """
    Загружает маршруты из файла routes.json (если он существует),
    иначе возвращает DEFAULT_ROUTES.
    """
    routes_filename = os.getenv("ROUTES_FILE", "routes.json")
    routes_file_path = BASE_DIR / routes_filename

    if routes_file_path.exists():
        try:
            with open(routes_file_path, "r", encoding="utf-8") as f:
                loaded = json.load(f)
                if isinstance(loaded, list) and len(loaded) > 0:
                    return loaded
        except Exception as e:
            print(f"[config] Предупреждение: Не удалось прочитать {routes_filename}: {e}")

    return DEFAULT_ROUTES


ROUTES = load_routes()
